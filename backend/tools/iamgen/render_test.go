package main

import (
	"testing"

	"github.com/stretchr/testify/require"
)

const wantHeader = `// Code generated by iamgen from backend/services/iam/pkg/authz. DO NOT EDIT.

import { createAccessControl } from "better-auth/plugins/access";
import {
  adminAc,
  defaultStatements,
  ownerAc,
} from "better-auth/plugins/organization/access";

type Inherited<Defaults, Resource extends string> = Resource extends keyof Defaults
  ? Defaults[Resource] extends readonly (infer Action extends string)[]
    ? Action
    : never
  : never;

function extend<
  Defaults extends object,
  Resource extends string,
  const Actions extends readonly string[],
>(defaults: Defaults, resource: Resource, actions: Actions) {
  const inherited: readonly string[] =
    (defaults as Record<string, readonly string[] | undefined>)[resource] ?? [];

  return [...new Set([...inherited, ...actions])] as (
    | Inherited<Defaults, Resource>
    | Actions[number]
  )[];
}
`

const wantFooter = `
export const roleNames = ["owner", "admin", "viewer"] as const;

export type Role = (typeof roleNames)[number];
`

func TestRender_ExtendsTheBetterAuthDefaultsOfEachResourceWithTheDomainPermissions(t *testing.T) {
	t.Parallel()

	m := matrix{
		statement: []permission{
			{"item", "read"}, {"item", "create"}, {"organization", "transfer"}, {"item", "delete"},
		},
		roles: []role{
			{"owner", "ownerAc", []permission{{"item", "read"}, {"organization", "transfer"}}},
			{"admin", "adminAc", []permission{{"item", "read"}}},
			{"viewer", "", []permission{{"item", "read"}}},
		},
	}

	require.Equal(t, wantHeader+`
export const statement = {
  ...defaultStatements,
  item: extend(defaultStatements, "item", ["read", "create", "delete"]),
  organization: extend(defaultStatements, "organization", ["transfer"]),
} as const;

export const ac = createAccessControl(statement);

export const roles = {
  owner: ac.newRole({
    ...ownerAc.statements,
    item: extend(ownerAc.statements, "item", ["read"]),
    organization: extend(ownerAc.statements, "organization", ["transfer"]),
  }),
  admin: ac.newRole({
    ...adminAc.statements,
    item: extend(adminAc.statements, "item", ["read"]),
  }),
  viewer: ac.newRole({
    item: ["read"],
  }),
} as const;
`+wantFooter, string(render(m)))
}

func TestRender_WithoutDomainPermissionsKeepsBetterAuthDefaults(t *testing.T) {
	t.Parallel()

	m := matrix{
		roles: []role{
			{"owner", "ownerAc", nil},
			{"admin", "adminAc", nil},
			{"viewer", "", nil},
		},
	}

	require.Equal(t, wantHeader+`
export const statement = {
  ...defaultStatements,
} as const;

export const ac = createAccessControl(statement);

export const roles = {
  owner: ac.newRole({
    ...ownerAc.statements,
  }),
  admin: ac.newRole({
    ...adminAc.statements,
  }),
  viewer: ac.newRole({}),
} as const;
`+wantFooter, string(render(m)))
}
