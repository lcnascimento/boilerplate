package main

import (
	"testing"

	"github.com/stretchr/testify/require"
)

func TestRender_MergesDomainPermissionsWithBetterAuthDefaults(t *testing.T) {
	t.Parallel()

	m := matrix{
		statement: []permission{
			{"note", "read"}, {"note", "create"}, {"tag", "read"}, {"note", "delete"},
		},
		roles: []role{
			{"owner", "ownerAc", []permission{{"note", "read"}, {"note", "create"}, {"tag", "read"}, {"note", "delete"}}},
			{"admin", "adminAc", []permission{{"note", "read"}, {"note", "create"}}},
			{"viewer", "", []permission{{"note", "read"}}},
		},
	}

	require.Equal(t, `// Code generated by iamgen from backend/services/iam/pkg/roles. DO NOT EDIT.

import { createAccessControl } from "better-auth/plugins/access";
import {
  adminAc,
  defaultStatements,
  ownerAc,
} from "better-auth/plugins/organization/access";

export const statement = {
  ...defaultStatements,
  note: ["read", "create", "delete"],
  tag: ["read"],
} as const;

export const ac = createAccessControl(statement);

export const roles = {
  owner: ac.newRole({
    ...ownerAc.statements,
    note: ["read", "create", "delete"],
    tag: ["read"],
  }),
  admin: ac.newRole({
    ...adminAc.statements,
    note: ["read", "create"],
  }),
  viewer: ac.newRole({
    note: ["read"],
  }),
} as const;

export const roleNames = ["owner", "admin", "viewer"] as const;

export type Role = (typeof roleNames)[number];
`, string(render(m)))
}

func TestRender_ExtendsBetterAuthDefaultResourcesInsteadOfReplacingThem(t *testing.T) {
	t.Parallel()

	m := matrix{
		statement: []permission{{"organization", "transfer"}, {"note", "read"}},
		roles: []role{
			{"owner", "ownerAc", []permission{{"organization", "transfer"}, {"note", "read"}}},
			{"admin", "adminAc", []permission{{"note", "read"}}},
			{"viewer", "", []permission{{"organization", "transfer"}}},
		},
	}

	require.Equal(t, `// Code generated by iamgen from backend/services/iam/pkg/roles. DO NOT EDIT.

import { createAccessControl } from "better-auth/plugins/access";
import {
  adminAc,
  defaultStatements,
  ownerAc,
} from "better-auth/plugins/organization/access";

export const statement = {
  ...defaultStatements,
  organization: [...defaultStatements.organization, "transfer"],
  note: ["read"],
} as const;

export const ac = createAccessControl(statement);

export const roles = {
  owner: ac.newRole({
    ...ownerAc.statements,
    organization: [...ownerAc.statements.organization, "transfer"],
    note: ["read"],
  }),
  admin: ac.newRole({
    ...adminAc.statements,
    note: ["read"],
  }),
  viewer: ac.newRole({
    organization: ["transfer"],
  }),
} as const;

export const roleNames = ["owner", "admin", "viewer"] as const;

export type Role = (typeof roleNames)[number];
`, string(render(m)))
}

