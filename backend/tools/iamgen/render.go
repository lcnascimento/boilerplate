package main

import (
	"fmt"
	"strings"
)

type permission struct {
	resource string
	action   string
}

type role struct {
	name               string
	betterAuthDefaults string
	permissions        []permission
}

type matrix struct {
	statement []permission
	roles     []role
}

const header = `// Code generated by iamgen from backend/services/iam/pkg/authz. DO NOT EDIT.

import { createAccessControl } from "better-auth/plugins/access";
import {
  adminAc,
  defaultStatements,
  ownerAc,
} from "better-auth/plugins/organization/access";

type Inherited<Defaults, Resource extends string> = Resource extends keyof Defaults
  ? Defaults[Resource] extends readonly (infer Action extends string)[]
    ? Action
    : never
  : never;

function extend<
  Defaults extends object,
  Resource extends string,
  const Actions extends readonly string[],
>(defaults: Defaults, resource: Resource, actions: Actions) {
  const inherited: readonly string[] =
    (defaults as Record<string, readonly string[] | undefined>)[resource] ?? [];

  return [...new Set([...inherited, ...actions])] as (
    | Inherited<Defaults, Resource>
    | Actions[number]
  )[];
}
`

func render(m matrix) []byte {
	var b strings.Builder

	b.WriteString(header)
	b.WriteString("\nexport const statement = {\n  ...defaultStatements,\n")
	writeEntries(&b, "  ", "defaultStatements", m.statement)
	b.WriteString("} as const;\n\nexport const ac = createAccessControl(statement);\n\nexport const roles = {\n")

	for _, r := range m.roles {
		if r.betterAuthDefaults == "" && len(r.permissions) == 0 {
			fmt.Fprintf(&b, "  %s: ac.newRole({}),\n", r.name)

			continue
		}

		fmt.Fprintf(&b, "  %s: ac.newRole({\n", r.name)

		if r.betterAuthDefaults != "" {
			fmt.Fprintf(&b, "    ...%s.statements,\n", r.betterAuthDefaults)
		}

		writeEntries(&b, "    ", defaultsOf(r), r.permissions)
		b.WriteString("  }),\n")
	}

	b.WriteString("} as const;\n\nexport const roleNames = [")

	for i, r := range m.roles {
		if i > 0 {
			b.WriteString(", ")
		}

		fmt.Fprintf(&b, "%q", r.name)
	}

	b.WriteString("] as const;\n\nexport type Role = (typeof roleNames)[number];\n")

	return []byte(b.String())
}

func defaultsOf(r role) string {
	if r.betterAuthDefaults == "" {
		return ""
	}

	return r.betterAuthDefaults + ".statements"
}

func writeEntries(b *strings.Builder, indent, defaults string, permissions []permission) {
	var resources []string

	actions := map[string][]string{}

	for _, p := range permissions {
		if _, seen := actions[p.resource]; !seen {
			resources = append(resources, p.resource)
		}

		actions[p.resource] = append(actions[p.resource], fmt.Sprintf("%q", p.action))
	}

	for _, resource := range resources {
		values := "[" + strings.Join(actions[resource], ", ") + "]"
		if defaults != "" {
			values = fmt.Sprintf("extend(%s, %q, %s)", defaults, resource, values)
		}

		fmt.Fprintf(b, "%s%s: %s,\n", indent, resource, values)
	}
}
